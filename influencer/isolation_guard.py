"""
隔離ガード ― 成人向け写真集の素材が、健全なインフルエンサー投稿へ混ざるのを止める。

なぜ必要か
  「あおい」は節約・ひとり暮らしを発信する健全キャラで、SNSと広告に出る。
  同じマシンの ai-influencer/ フォルダでは、まったく別事業として
  成人向け(R-18)写真集を作っている。この2つが1枚でも混ざると、
  ・SNSアカウントが即凍結される
  ・広告・アフィリエイトの提携が切られる
  ・決済手段(Wise/PayPal)がアダルト禁止のため止まる
  という、あとから取り返しのつかない事故になる。

  人間は急いでいるとフォルダを打ち間違える。だから「気をつける」ではなく
  機械が止める形にしてある。

やること
  投稿・動画づくりが読み込むフォルダを検査し、
  ① 健全側フォルダ(influencer/)の外を指している
  ② 成人向けを示す言葉を含む
  のどちらかなら、その場で止める。★迷ったら通さない側に倒す。
"""

import os

# このファイルが置かれている場所＝健全側の境界線
健全側の根 = os.path.dirname(os.path.abspath(__file__))

# 成人向け側にだけ現れる言葉。1つでも当たれば止める。
成人向けの目印 = (
    "photobook",      # 写真集の生成・仕上げ
    "output_photobook",
    "censored",       # モザイク済み
    "mosaic",         # モザイク処理
    "ai-influencer",  # 成人向け工房のフォルダ名
    "_pack",          # FANZA提出パック
    "adult",
    "r18",
    "r-18",
    "fanza",
)


class 隔離違反(Exception):
    """成人向け素材へ手が伸びたときに投げる。握りつぶさないこと。"""


def 素材フォルダを検査する(パス, 用途="この処理"):
    """写真を読み込むフォルダが健全側かどうかを確かめる。

    問題なければ、正規化した絶対パスを返す。
    少しでも成人向けに触れていれば 隔離違反 を投げて止める。
    """
    if not パス:
        raise 隔離違反("%s: 素材フォルダが指定されていません。" % 用途)

    絶対パス = os.path.realpath(os.path.abspath(os.path.expanduser(パス)))
    小文字 = 絶対パス.lower()

    # ① 成人向けの目印を含むか（シンボリックリンクを辿ったあとで見る）
    for 目印 in 成人向けの目印:
        if 目印 in 小文字:
            raise 隔離違反(
                "★止めました: %s に成人向け側のフォルダが指定されています。\n"
                "  指定されたのは: %s\n"
                "  当たった言葉  : 「%s」\n"
                "  成人向け写真集と健全なSNS投稿は完全に別事業です。\n"
                "  1枚でも混ざるとアカウント凍結・提携解除になるため、ここで停止します。\n"
                "  健全な写真は %s の中だけを使ってください。"
                % (用途, 絶対パス, 目印, 健全側の根)
            )

    # ② 健全側フォルダの外を指していないか
    根 = os.path.realpath(健全側の根)
    if not (絶対パス == 根 or 絶対パス.startswith(根 + os.sep)):
        raise 隔離違反(
            "★止めました: %s が健全側フォルダの外を指しています。\n"
            "  指定されたのは: %s\n"
            "  許される範囲  : %s の中だけ\n"
            "  外の写真を使う必要がある場合は、いったん健全側へコピーし、\n"
            "  成人向けでないことを目で確かめてから実行してください。"
            % (用途, 絶対パス, 根)
        )

    return 絶対パス


def 画像が健全側のものか確かめる(画像パスの一覧, 用途="この処理"):
    """個々の画像ファイルも1枚ずつ確かめる。
    フォルダ検査を通っても、シンボリックリンクで外の画像が
    紛れ込むことがあるため、最後にもう一度見る（二重の歯止め）。"""
    for p in 画像パスの一覧:
        素材フォルダを検査する(p, 用途)
    return 画像パスの一覧
