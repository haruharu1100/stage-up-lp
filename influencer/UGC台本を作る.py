def 環境を読む(名前):
    """automation/.env から1つだけ値を取り出す。中身は表示しない。"""
    if os.environ.get(名前):
        return os.environ[名前]
    if not os.path.exists(環境ファイル):
        return None
    for 行 in open(環境ファイル, encoding="utf-8"):
        行 = 行.strip()
        if 行.startswith(名前 + "="):
            return 行.split("=", 1)[1].strip().strip('"').strip("'")
    return None


