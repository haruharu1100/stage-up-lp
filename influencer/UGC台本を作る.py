# ══════════════════════════════════════════ 台帳（A/Bテスト）

def 台帳を読む():
    if os.path.exists(台帳パス):
        return json.load(open(台帳パス, encoding="utf-8"))
    return {"_説明": "同じ顔のまま『見せ方』だけ変えた動画の成績表。"
                 "投稿したあと、再生数・視聴維持率・クリックを手で書き込む。"
                 "20本たまるまでは判断しない（アルゴリズムの学習が回らないため）。",
            "_判断の目安": "1本ずつ見ない。切り口ごと・見せ方ごとに束ねて、"
                     "中央値で比べる。1本だけ跳ねたものを正解と決めない。",
            "作品": []}


def 台帳に足す(台帳, 記録):
    台帳["作品"].append(記録)
    json.dump(台帳, open(台帳パス, "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)


def 台帳を見せる():
    台帳 = 台帳を読む()
    作品 = 台帳["作品"]
    if not 作品:
        print("\nまだ1本も登録されていません。")
        print("  python3 UGC台本を作る.py  で作ってください。\n")
        return
    投稿済み = [x for x in 作品 if x.get("再生数") is not None]
    print("\n══ A/Bテスト台帳 ══")
    print("作った本数: %d本 ／ 成績を記入済み: %d本" % (len(作品), len(投稿済み)))
    if len(投稿済み) < 20:
        print("\n★まだ%d本ぶんの成績しかありません。"
              "20本たまるまで、伸びる／伸びないの判断はしないでください。"
              % len(投稿済み))
        print("  （アルゴリズムが『このアカウントを誰に見せるか』を"
              "学ぶ前に判断すると、たまたまの数字に振り回されます）")
    for 軸 in ["切り口", "見せ方"]:
        束 = {}
        for x in 投稿済み:
            束.setdefault(x[軸], []).append(x["再生数"])
        if not 束:
            continue
        print("\n【%s別・再生数の中央値】" % 軸)
        for k, v in sorted(束.items(),
                           key=lambda kv: -sorted(kv[1])[len(kv[1]) // 2]):
            中央 = sorted(v)[len(v) // 2]
            print("  %-10s 中央値 %8s （%d本）" % (k, f"{中央:,}", len(v)))
    print()


