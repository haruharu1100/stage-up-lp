# ══════════════════════════════════════════ 検査（作ったあと必ず通す）

def 検査する(台本, 許可数字, items):
    """台本を機械で検査する。1つでも引っかかったら作り直し。

    戻り値: 問題の一覧（空なら合格）"""
    問題 = []
    全文 = " ".join(台本[k] for k in
                  ["フック", "問題提起", "解決策", "証拠", "CTA"] if 台本.get(k))

    for w in 実体験の言葉:
        if w in 全文:
            問題.append("体験のふり『%s』が入っている（AIキャラなので不可）" % w)

    # 「使った」系は、すぐ後ろに何が来るかで判断する。
    #   「使ったデータ量」＝視聴者の話なので可。
    #   「使った楽天モバイル」「使ったプラン」＝あおいの体験談になるので不可。
    for w in 対象しだいの言葉:
        for m in re.finditer(re.escape(w), 全文):
            後ろ = 全文[m.end():m.end() + 6]
            if any(後ろ.startswith(o) for o in 使ってよい対象):
                continue
            問題.append(
                "体験のふりの疑い『%s%s…』（%s のような視聴者の話なら可）"
                % (w, 後ろ[:4], "使ったデータ量"))

    for w in 危ない言葉:
        if w in 全文:
            問題.append("断定・誇大『%s』が入っている（景表法）" % w)
    for it in items:
        for w in it.get("ng_phrases", []):
            if w in 全文:
                問題.append("%s の禁止語『%s』が入っている" % (it["name"], w))

    # 数字の検査。台本に出た数字が、データにも計算結果にも無ければ嘘。
    for m in re.findall(r"\d[\d,]*", 全文):
        n = m.replace(",", "")
        if n in 許可数字:
            continue
        if len(n) <= 2 and int(n) <= 60:
            continue          # 「3秒」「5回線」など、料金でない小さい数は通す
        問題.append("データに無い数字『%s』が入っている（作られた金額の疑い）" % m)

    # 長さ。読み上げて45秒に収まらないものは、最後まで見てもらえない。
    字数 = len(re.sub(r"\s", "", 全文))
    if 字数 > 320:
        問題.append("長すぎる（%d字／45秒に入らない）" % 字数)
    if 字数 < 90:
        問題.append("短すぎる（%d字／内容が薄い）" % 字数)
    if 台本.get("フック") and len(台本["フック"]) > 34:
        問題.append("フックが長い（%d字／3秒で言い切れない）" % len(台本["フック"]))
    return 問題


