def 数字を集める(items):
    """台本に出してよい数字の一覧を作る。

    ★ここに無い数字が台本に出てきたら、それはAIが作った嘘なので落とす。"""
    許可 = set()
    for it in items:
        for 値 in it.values():
            if isinstance(値, str):
                for m in re.findall(r"\d[\d,]*", 値):
                    許可.add(m.replace(",", ""))
            elif isinstance(値, int):
                許可.add(str(値))
            elif isinstance(値, list):
                for s in 値:
                    if isinstance(s, str):
                        for m in re.findall(r"\d[\d,]*", s):
                            許可.add(m.replace(",", ""))
    # 差額・年額は、こちらで計算したぶんだけ足す（AIには計算させない）
    月額 = sorted(it["monthly_min_jpy"] for it in items
                if isinstance(it.get("monthly_min_jpy"), int))
    if len(月額) >= 2:
        差 = 月額[-1] - 月額[0]
        許可.add(str(差))
        許可.add(str(差 * 12))
        許可.add(str(月額[0] * 12))
        許可.add(str(月額[-1] * 12))
    return 許可, (月額[-1] - 月額[0] if len(月額) >= 2 else None)


def 材料を作る(items, 型名):
    """切り口ごとに、使う事実を機械で選ぶ。★AIには選ばせない。"""
    使える = [it for it in items if isinstance(it.get("monthly_min_jpy"), int)]

    # ★「基本料0円＋あとで買い足す」型は、金額くらべの最安から外す。
    #   povo 2.0 の0円は基本料だけで、データを使うにはトッピングを買う。
    #   これを「いちばん安い月額」として他社の通常プランと並べると、
    #   同じ条件で比べていないのに安く見える＝有利誤認になる。
    #   （外すだけで黙らせない。下の「金額くらべから外した会社」で必ず触れる）
    def 買い足しが要る(it):
        表示 = it.get("monthly_display", "") + it.get("monthly_note", "")
        return "トッピング" in 表示 or "買い足" in 表示

    並べる = [it for it in 使える if not 買い足しが要る(it)] or 使える
    外した = [it for it in 使える if 買い足しが要る(it)]

    安い順 = sorted(並べる, key=lambda x: x["monthly_min_jpy"])
    最安, 最高 = 安い順[0], 安い順[-1]
    差額 = 最高["monthly_min_jpy"] - 最安["monthly_min_jpy"]

    共通 = {
        "確認日": items[0].get("checked_at", ""),
        "会社数": len(items),
        "並べた数": len(安い順),
        "最安社": 最安["name"], "最安額": 最安["monthly_min_jpy"],
        "最安表示": 最安.get("monthly_display", ""),
        "最高社": 最高["name"], "最高額": 最高["monthly_min_jpy"],
        "差額": 差額, "年差額": 差額 * 12,
        "外した社": "・".join(it["name"] for it in 外した),
    }

    if 型名 == "見落とし":
        # 注記（小さい字）に条件が書いてあるものを探す
        候補 = [it for it in items
              if it.get("initial_fee_note") and re.search(r"\d", it["initial_fee_note"])]
        候補 = 候補 or [it for it in items if it.get("call_note")]
        主役 = 候補[0] if 候補 else 最安
        共通["主役"] = 主役["name"]
        共通["見落とし本文"] = (主役.get("initial_fee_note")
                          or 主役.get("call_note") or "")
        共通["表の顔"] = 主役.get("initial_fee_display", "")
        共通["出典"] = 主役.get("monthly_source") or 主役.get("call_source", "")
    elif 型名 == "常識否定":
        主役 = 最安
        共通["主役"] = 主役["name"]
        共通["短所"] = 主役.get("demerits", [""])[0]
        共通["長所"] = 主役.get("merits", [""])[0]
        共通["向く人"] = 主役.get("fit", "")
