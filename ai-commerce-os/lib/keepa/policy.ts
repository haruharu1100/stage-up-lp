/**
 * 文字列からAPIキーらしきものを消す。ログ・保存・画面表示の直前に必ず通す。
 *
 * リクエストURLには `key=...` が入るので、**URLをそのまま保存しない**。
 * この関数は最後の保険であって、一次の対策は「URLを保存しないこと」である。
 */
export function redactKeepaKey(text: string, key?: string | null): string {
  let out = String(text ?? '');
  if (key && key.length >= 8) {
    // 実際のキー文字列が混ざっていたら、まるごと伏せる。
    out = out.split(key).join('[REDACTED]');
  }
  // key= の後ろに続く英数字を伏せる（URLやクエリ文字列の形で出てきた場合）。
  out = out.replace(/([?&](?:key|apikey|api_key|token)=)[^&\s"']+/gi, '$1[REDACTED]');
  return out;
}

