/**
 * 「この道具を、本番の保存先へ向けない」を1か所にまとめたもの。
 *
 * ═══════════════════════════════════════════════════════
 * ★なぜ1か所にするのか
 * ═══════════════════════════════════════════════════════
 *
 *   同じ停止装置が、いま14本の道具に書き写されています。
 *   書き写しは、片方だけ直った日にすり抜けます。
 *
 *   新しく作る道具は、これを呼んでください。
 *   （すでにある道具を、いま一斉に書き換えることはしません。
 *     動いているものを触るほうが、事故が増えるからです）
 *
 * ═══════════════════════════════════════════════════════
 * ★「読むだけだから安全」と考えないこと
 * ═══════════════════════════════════════════════════════
 *
 *   読むだけの道具でも、本番へ向ければ、
 *   お客様の氏名・メール・住所が、そのまま画面に出ます。
 *   その画面は、報告文に貼られます。報告文は残ります。
 *
 *   そして、読むだけの道具は、明日には書く道具になります。
 *   「1行足すだけ」で書けてしまうからです。
 *   ですので、読むだけのものにも、同じ停止装置を付けます。
 */

/**
 * 本番の保存先に見えたら、何もせずに止める。
 *
 * @param {string} naze この道具が何をするものかを、日本語で1行。
 *                      止まったときの画面に、そのまま出ます。
 */
export function honbanNiMukenai(naze) {
  const nafuda = String(
    process.env.DATABASE_ENV ?? process.env.VERCEL_ENV ?? "",
  )
    .trim()
    .toLowerCase();
  const url = String(process.env.DATABASE_URL ?? "").trim();

  /* 名札と、つなぎ先の名前の、両方を見ます。
     どちらか片方が設定し忘れでも、もう片方で止めるためです。 */
  const nafudaGaHonban = nafuda === "production";
  const namaeGaHonban = /prod/i.test(url);

  if (!nafudaGaHonban && !namaeGaHonban) return;

  console.error(
    [
      "",
      "  この道具は、本番の保存先へは向けられません。",
      "",
      `    やろうとしたこと : ${naze}`,
      `    いまのつなぎ先   : ${url === "" ? "（未設定）" : url}`,
      `    いまの名札       : ${nafuda === "" ? "（無し）" : nafuda}`,
      "",
      "  本番のデータには、お客様の氏名・メール・住所が入っています。",
      "  画面に出した時点で、それは報告文にも残ります。",
      "",
      "  検証用の保存先に向けてから、もう一度実行してください。",
      "    npx vercel env pull .env.local --environment=preview --yes",
      "",
    ].join("\n"),
  );
  process.exit(1);
}
