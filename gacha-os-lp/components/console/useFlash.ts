/**
 * 画面上部の知らせを、放っておいても消す係。
 *
 * ═══════════════════════════════════════════════
 * ★何を直しているのか
 * ═══════════════════════════════════════════════
 *
 *   これまで、知らせは「閉じる」を押すまで消えませんでした。
 *   その結果、こうなっていました。
 *
 *       ガチャをまわす  → 「C賞でした」
 *       発送の画面へ移動 → 「C賞でした」がまだ上に出ている
 *       問い合わせへ移動 → まだ出ている
 *
 *   お客様も運営の方も、画面の上に出ている文は
 *   「いま見ている画面の話」だと思って読みます。
 *   ガチャの結果が発送の画面の上に出ていれば、
 *   発送で何かが起きたのだと読み違えます。
 *
 * ═══════════════════════════════════════════════
 * ★消え方は2つ
 * ═══════════════════════════════════════════════
 *
 *   ① 数秒たったら消える（FLASH_MS）
 *   ② 画面を移ったら消える
 *
 *   ②が要る理由は、①だけだと、6秒たつ前に画面を移った人には
 *   前の画面の知らせが付いてくるからです。
 *   逆に②だけだと、同じ画面に留まっている限り永久に残ります。
 *   両方あって、はじめて「今の合図」になります。
 *
 * ═══════════════════════════════════════════════
 * ★直すときの注意
 * ═══════════════════════════════════════════════
 *
 *   ・時間を2〜3秒に縮めないこと。
 *     日本語で40字ほどの文は、読み終えるまでに数秒かかります。
 *     読み終える前に消える知らせは、出していないのと同じです。
 *
 *   ・「閉じる」ボタンを外さないこと。
 *     読み終えた人が、すぐ本文に戻れる道が要ります。
 *     消えるまで待たされるのは、それはそれで邪魔です。
 *
 *   ・大事な事実を、この帯だけで伝えないこと。
 *     消えるものは、必ず見逃されます。
 *     後から確かめる必要があるものは、お知らせ一覧か
 *     監査ログにも残します。ここは合図だけです。
 */

import { useEffect, useRef } from "react";

import { FLASH_MS, type Flash } from "@/lib/console/state";

/**
 * 知らせが出たら、FLASH_MS 後に自分で消す。
 * 画面が変わったときも消す。
 *
 * @param flash いま出ている知らせ（無ければ null）
 * @param key   いま見ている画面を表す文字列。変われば移動したとみなす。
 * @param clear 知らせを消すときに呼ぶ処理
 *
 * ★2つを1つの道具にまとめてある理由。
 *   別々にすると、片方だけ付けた画面が必ず出ます。
 *   時間だけの画面は、6秒たつ前に移動すると知らせが付いてきます。
 *   移動だけの画面は、同じ画面に居る限り永久に残ります。
 *   どちらも「直したつもり」で直っていません。
 */
export function useFlash(
  flash: Flash | null,
  key: string,
  clear: () => void,
) {
  /* ★消す処理を、そのまま見張り対象にしないこと。
       画面が描き直されるたびに新しい関数になるので、
       数え直しが毎回やり直しになり、いつまでも消えません。
       中身だけ差し替えて、見張り対象からは外します。 */
  const doClear = useRef(clear);
  doClear.current = clear;

  /* ── ① 数秒たったら消える ── */
  /* ★合図を「文」にしないこと。
       同じ文の知らせは続けて出ます（「C賞でした」を2回）。
       文で見ていると2回目は「変わっていない」ことになり、
       1回目の数え直しがそのまま進んで、
       2回目の知らせが出た直後に消えます。
       だから、知らせ1つずつに振ってある通し番号（at）で見ます。 */
  const at = flash?.at ?? 0;

  useEffect(() => {
    if (!at) return;
    const t = window.setTimeout(() => doClear.current(), FLASH_MS);
    /* ★片付けを忘れないこと。
         画面を移ったのに前の数え直しが残っていると、
         次に出した知らせを、前の数え直しが消しにきます。 */
    return () => window.clearTimeout(t);
  }, [at]);

  /* ── ② 画面を移ったら消える ── */
  /* ★最初に開いたときは消さないこと。
       ログインした直後の「◯◯としてログインしました」は、
       最初の画面が出るのと同時に出ます。
       画面が出たことを「移動」と数えると、その知らせが即座に消えます。 */
  const seen = useRef<string | null>(null);

  useEffect(() => {
    if (seen.current === null) {
      seen.current = key;
      return;
    }
    if (seen.current === key) return;
    seen.current = key;
    doClear.current();
  }, [key]);
}
