/**
 * 試験用のDBを用意する。
 *
 * ★試験が本番のDBに触れないようにすること。
 *   同時抽選の試験は1000回ぶんのポイントを動かします。
 *   接続先を間違えると、本番のお客様の残高が動きます。
 *
 *   そこで、このファイルを読み込んだ時点で接続先を
 *   使い捨ての一時ファイルに固定します。
 *   環境変数に本番のURLが入っていても、必ず上書きします。
 */

import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const dir = mkdtempSync(path.join(tmpdir(), "gacha-os-test-"));

process.env.DATABASE_URL = `file:${path.join(dir, "t.db")}`;
process.env.DATABASE_ENV = "test";
delete process.env.DATABASE_AUTH_TOKEN;

/** 試験用DBの置き場所（後片付けのために出しておく） */
export const TEST_DB_DIR = dir;

/**
 * 後片付けについて。
 *
 * ★終了時（process.on("exit")）にフォルダごと消さないこと。
 *   DBの接続はまだファイルを開いたままなので、
 *   開いている最中に土台を消すことになり、
 *   後片付けの最中に異常終了します（SIGSEGV）。
 *
 *   そうなると、中の試験は全部通っているのに、
 *   まとめだけが「失敗」と出ます。
 *   原因が試験の中身に見えるので、いちばん時間を取られる壊れ方です。
 *
 *   一時フォルダは、OSが後で回収します。数百KBなので放っておきます。
 *   どうしても消したいときは、接続を閉じてから消してください。
 */
/**
 * ═══════════════════════════════════════════════
 * ★ここに「終わり方を早める仕掛け」を入れないこと
 * ═══════════════════════════════════════════════
 *
 *   以前、ここに次の1行を置いていました。
 *
 *       process.on("beforeExit", () => process.exit(process.exitCode ?? 0));
 *
 *   狙いは、DBの部品（@libsql/client の機械語で書かれた部分）の
 *   後片付けで異常終了（SIGSEGV）するのを避けることでした。
 *
 *   ★これは外しました。理由は2つあります。
 *
 *     ① 効いていませんでした。
 *        目印を仕込んで調べたところ、落ちた回は、
 *        この行に一度も入っていませんでした。
 *        つまり、終わりぎわではなく、その手前で落ちていました。
 *
 *     ② 合否のまとめを消していました。
 *        試験の結果は、最後に「# tests / # pass / # fail」で
 *        締めくくられます。この行はその締めくくりより先に
 *        プロセスを終わらせてしまい、
 *        「何本走ったのか分からない」状態を作っていました。
 *        ★数えられない結果は、通ったことにできません。
 *
 *   本当の対処は scripts/run-tests.mjs 側にあります
 *   （1ファイルにつき1プロセス。締めくくりを見届けてから、
 *     後片付けだけを待たずに終わらせる）。
 *
 *   ★このファイルは試験専用です。本番の起動経路では読み込みません。
 */

export function removeTestDbDir(): void {
  try {
    rmSync(dir, { recursive: true, force: true });
  } catch {
    /* 消せなくても試験の結果には関わらない */
  }
}
