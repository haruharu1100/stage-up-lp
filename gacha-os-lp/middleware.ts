/**
 * 入口から出ていく答えに、「これは保存してよいものではありません」と書く。
 *
 * ═══════════════════════════════════════════════════════
 * ★なぜ、これが要るのか（2026-08-26、公開先で見つかりました）
 * ═══════════════════════════════════════════════════════
 *
 *   ログインが要る入口（/api/**）の答えに、こう書かれていました。
 *
 *       cache-control: public, max-age=0, must-revalidate
 *
 *   画面（/mypage など）のほうは正しく
 *
 *       private, no-cache, no-store, max-age=0, must-revalidate
 *
 *   になっていたので、見落としていました。
 *   入口だけが、ちがっていました。
 *
 *   ここで効いてくるのは、先頭の1語です。
 *
 *       private … その人のブラウザだけが持っていてよい
 *       public  … 途中にある機械が持っていてよい
 *
 *   「途中にある機械」というのは、たとえば
 *   会社や学校の共有プロキシ、キャッシュ付きのCDN、
 *   セキュリティ製品の中にある中継役です。
 *
 *   /api/auth/me の中身は、その人が誰で、どの会社の、
 *   どの役職かという答えです。
 *   /api/customer/points は残高、/api/console/audit は監査ログです。
 *
 *   これを「途中の機械が持っていてよい」と、こちらから
 *   書いて渡していたことになります。
 *
 *   max-age=0, must-revalidate があるので、
 *   ふつうは そのまま次の人に渡されることはありません。
 *   ですが「持っていてよい」と言っている以上、
 *   持たれます。持たれたものは、いつか漏れます。
 *   しかも漏れたとき、こちらの記録には何も残りません。
 *
 *   ★人によって中身が変わるものは、no-store にすること。
 *     「短い時間なら大丈夫」ではありません。
 *     残高と役職と監査ログは、1秒でも他人の機械に置かない。
 *
 * ═══════════════════════════════════════════════════════
 * ★なぜ、各入口に1行ずつ書かないのか
 * ═══════════════════════════════════════════════════════
 *
 *   入口は30本あります。1本ずつ書くと、31本目で忘れます。
 *   忘れても画面は正しく動くので、誰も気づきません。
 *
 *   だから、通り道に1か所だけ置きます。
 *   新しい入口を足した人が、何も知らなくても、正しくなります。
 *
 *   戻されていないかは scripts/check-cache.mjs が
 *   公開前に見張ります（npm run build で必ず走ります）。
 */

import { NextResponse, type NextRequest } from "next/server";

export function middleware(req: NextRequest) {
  const res = NextResponse.next();

  /**
   * ★no-store と private を、両方書くこと。
   *
   *   no-store … どこにも保存しない
   *   private  … 万一 no-store を読み落とす古い機械があっても、
   *              せめて共有の置き場には入れない
   *
   *   Pragma と Expires は、古い中継役のためです。
   *   いまどき要らないように見えますが、
   *   途中に何が挟まっているかは、こちらからは見えません。
   */
  res.headers.set(
    "Cache-Control",
    "private, no-store, no-cache, max-age=0, must-revalidate",
  );
  res.headers.set("Pragma", "no-cache");
  res.headers.set("Expires", "0");

  /**
   * ★Vary: Cookie も付けます。
   *   万一どこかで保存されたとき、
   *   「クッキーが違えば別物」と分かるようにしておくためです。
   *
   *   ★ただし、正直に書いておきます（2026-08-26 実測）。
   *     ここで書いた Vary は、このあと Next.js 自身が
   *     Vary: RSC, Next-Router-State-Tree, Next-Router-Prefetch
   *     で上書きすることがあります。公開先で実際にそうなりました。
   *
   *     つまり Vary は当てにできません。
   *     守っているのは、上の no-store です。
   *     Vary は「no-store が効かなかったときの保険」であって、
   *     主役ではありません。ここを取り違えないこと。
   */
  res.headers.set("Vary", "Cookie");

  return res;
}

/**
 * ★ここに /api/:path* 以外を足すときは、よく考えること。
 *
 *   お客様に配る画像やCSSまで no-store にすると、
 *   毎回ぜんぶ読み直しになり、表示が遅くなります。
 *   表示速度は検索順位に効きます。
 *
 *   人によって中身が変わるものだけを、ここに入れます。
 *   画面（/mypage など）は Next.js が既に
 *   private, no-store を付けているので、ここには要りません。
 */
export const config = {
  matcher: ["/api/:path*"],
};
