/**
 * 練習用の決済（Mock）。
 *
 * ═══════════════════════════════════════════════════════
 * ★これは何のためにあるのか
 * ═══════════════════════════════════════════════════════
 *
 *   決済会社と契約する前でも、
 *
 *     ポイント商品を作る → 買う → ポイントが増える → ガチャを引く
 *
 *   の通し確認ができるようにするためのものです。
 *   お金は1円も動きません。外部へも1回も通信しません。
 *
 * ═══════════════════════════════════════════════════════
 * ★ここで「設定OK」を返している理由
 * ═══════════════════════════════════════════════════════
 *
 *   Mock に足りない設定はありません。ですので preflight は ok:true です。
 *
 *   「本番で Mock を使わせない」という判断は、
 *   ここではなく lib/server/payments/index.ts に1か所だけ置いています。
 *
 *   ★ここにも同じ判断を書き足さないこと。
 *     2か所になった時点で、片方だけ直した日に必ずずれます。
 *
 * ═══════════════════════════════════════════════════════
 * ★「支払ったことにする」入口について
 * ═══════════════════════════════════════════════════════
 *
 *   app/api/customer/point-orders/mock-pay/ が、その入口です。
 *   あの入口は二重に閉じてあります。
 *
 *     ① 決済業者が mock でなければ 404（存在自体を知らせない）
 *     ② 本番の保存先なら 403（MOCK_IN_PRODUCTION）
 *
 *   ★どちらか片方だけにしないこと。
 *     ①だけだと、設定を間違えた本番でポイントが作れます。
 */

import type { PaymentPreflight, PaymentProviderImpl } from "./types";

export class MockPaymentProvider implements PaymentProviderImpl {
  readonly name = "mock" as const;
  readonly kind = "MOCK" as const;

  /* ★環境変数を受け取らないのは、練習用に必要な設定が1つも無いからです。
       約束（PaymentProviderImpl）の側は受け取る形にしてありますが、
       使わない引数をここに残すと、決まりの検査で止まります。 */
  preflight(): PaymentPreflight {
    return {
      ok: true,
      provider: this.name,
      note:
        "練習用の決済です。お金は1円も動きません。外部へも通信しません。" +
        "本番では使えません（本番では必ず止まります）。",
    };
  }
}
