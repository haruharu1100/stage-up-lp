/**
 * メールの送り口。
 *
 * ═══════════════════════════════════════════════════════
 * ★確認用（Preview）では、本当に送らないこと
 * ═══════════════════════════════════════════════════════
 *
 *   確認用のデータには、架空のお名前が入っています。
 *   ですが、メールアドレスの打ち間違いは必ず起きます。
 *   1文字違いのアドレスが実在すれば、それは他人に届きます。
 *
 *   届いた人にとっては、身に覚えのない
 *   「パスワードの再設定」のメールです。
 *   こちらの確認作業のために、他人を不安にさせることになります。
 *
 *   ★だから、確認用では送りません。サーバーの記録に書くだけにします。
 *     記録は運営者だけが読めます。動きの確認はそれでできます。
 *
 * ═══════════════════════════════════════════════════════
 * ★本文を、そのまま画面へ返さないこと
 * ═══════════════════════════════════════════════════════
 *
 *   「確認用なので、再設定のリンクを画面に出せば早い」
 *   これをやると、メールアドレスを入れただけの人に
 *   リンクが渡ります。つまり、誰でも誰にでも成りすませます。
 *
 *   確認用であっても、そこは同じにしません。
 *
 * ═══════════════════════════════════════════════════════
 * ★いまできること／これからやること
 * ═══════════════════════════════════════════════════════
 *
 *   いまできること：
 *     送る中身を1か所にまとめ、宛先と本文を記録に残す。
 *     入口から先の流れ（申込→リンク→再設定）は、本番と同じ形で動く。
 *
 *   これからやること：
 *     本番では、ここに実際の送信（SMTP など）をつなぐ。
 *     つなぐ場所はこの1か所だけなので、呼び出し側は変わりません。
 */

/** 送るもの */
export type Mail = {
  to: string;
  subject: string;
  body: string;
};

/** どう送ったか */
export type Delivery = {
  /** "LOG" = 記録に書いただけ（確認用）／"SENT" = 実際に送った */
  via: "LOG" | "SENT";
};

/**
 * いま、本当に送ってよい状態か。
 *
 * ★既定を「送る」にしないこと。
 *   設定を1つ入れ忘れただけで、確認作業のメールが
 *   実在する誰かへ飛びます。
 *   はっきり本番だと分かるときだけ、送ります。
 */
function reallySend(): boolean {
  const env = (process.env.DATABASE_ENV ?? "").trim().toLowerCase();
  return env === "production" && Boolean(process.env.MAIL_SMTP_URL);
}

/**
 * メールを届ける（本番）／記録に書く（確認用）。
 *
 * ★戻り値で本文を返さないこと。
 *   呼び出し側が、うっかり画面へ出せてしまいます。
 */
export async function deliver(mail: Mail): Promise<Delivery> {
  if (!reallySend()) {
    /* ★宛先と件名だけでなく、本文も残すこと。
         リンクが正しく作れているかを、ここでしか確かめられません。
         この記録を読めるのは、サーバーの記録を見られる人だけです。 */
    console.info(
      [
        "──────── メール（確認用・実際には送っていません） ────────",
        `宛先　： ${mail.to}`,
        `件名　： ${mail.subject}`,
        "本文　：",
        mail.body,
        "────────────────────────────────────────────",
      ].join("\n"),
    );
    return { via: "LOG" };
  }

  /*
   * ★ここに実際の送信をつなぐまで、本番では使わないこと。
   *   「送ったつもりで送れていない」がいちばん危ないので、
   *   黙って成功を返さず、はっきり止めます。
   */
  throw new Error(
    "本番のメール送信は、まだつないでいません（lib/server/mailer.ts）。",
  );
}
