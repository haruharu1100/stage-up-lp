/**
 * 本番の抽選に使う乱数（CSPRNG）。
 *
 * ═══════════════════════════════════════════════════════
 * ★これまで何が危なかったのか
 * ═══════════════════════════════════════════════════════
 *
 *   以前は、乱数の種を
 *
 *       ガチャID  ＋  そのガチャが今までに引かれた回数
 *
 *   から作っていました。どちらもお客様の画面に出ている情報です。
 *   つまり、外の人が同じ計算をやり直せば、
 *   「次に何が出るか」「あと何回目にS賞が出るか」が全部分かります。
 *
 *   S賞が出る回だけを狙って引くことができてしまう、ということです。
 *   これは、オンラインガチャで最もやってはいけない作りです。
 *
 * ═══════════════════════════════════════════════════════
 * ★これからの決まり
 * ═══════════════════════════════════════════════════════
 *
 *   1) 抽選は運営側（サーバー）でだけ行う。お客様の端末では行わない。
 *   2) 乱数は node:crypto の randomInt / randomBytes だけを使う。
 *   3) 次の材料を、抽選の乱数に使わない。
 *        Math.random()  … 予測できる方式のことがある
 *        固定の種       … 同じ並びが繰り返される
 *        ガチャID       … 公開情報
 *        抽選回数       … 公開情報
 *        時刻だけ       … 秒単位なら総当たりで当てられる
 *   4) 抽選が終わったら、乱数の呼び出し1回ぶんの控え（nonce）を記録に残す。
 *      これは結果を再現するためではなく、
 *      「この1回が確かに1回だけ行われた」ことを示すためのもの。
 *
 * ═══════════════════════════════════════════════════════
 * ★なぜ「種を保存して後から再現」をやめたのか
 * ═══════════════════════════════════════════════════════
 *
 *   再現できるということは、予測もできるということです。
 *   後から検証したいのなら、種ではなく「結果そのもの」を
 *   改ざん検知つきの監査ログに残せば足ります。
 *   実際そうしています（lib/server/audit.ts）。
 */

import { randomBytes, randomInt } from "node:crypto";

/**
 * 0 以上 n 未満の整数を、偏りなく1つ選ぶ。
 *
 * randomInt は内部で「範囲に収まるまで引き直す」方式を使っているので、
 * 2 の累乗でない範囲でも偏りません。
 * （randomBytes の余りを取る書き方は、小さい数字がわずかに出やすくなります）
 */
export function pickBelow(n: number): number {
  const size = Math.max(1, Math.floor(n));
  if (size <= 1) return 0;
  return randomInt(0, size);
}

/** 1回の抽選につき1つ発行する控え。記録の中で抽選を一意に指すために使う */
export function nonce(): string {
  return randomBytes(16).toString("hex");
}

