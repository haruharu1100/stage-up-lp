/**
 * 「いま本番か」を、システム全体でここ1か所だけで決める。
 *
 * ═══════════════════════════════════════════════════════
 * ★なぜ1か所にまとめたのか
 * ═══════════════════════════════════════════════════════
 *
 *   メールにも決済にも、まったく同じ判定が必要です。
 *   それぞれのファイルに書くと、こうなります。
 *
 *     ・片方だけ直す
 *     ・片方は「本番」、もう片方は「本番ではない」と判断する
 *     ・メールは止まるのに、決済は通ってしまう（またはその逆）
 *
 *   お金とメールで判定がずれるのが、いちばん危ない壊れ方です。
 *   ですので、判定はこの1つの関数だけにします。
 *
 * ═══════════════════════════════════════════════════════
 * ★どちらか一方でも production なら本番
 * ═══════════════════════════════════════════════════════
 *
 *   「DATABASE_ENV は production だが VERCEL_ENV は preview」
 *   のような食い違いは、設定を移し替えるたびに必ず起きます。
 *
 *   ゆるいほうに寄せると、本番で確認用（Mock）が動きます。
 *   ですので、きついほうに寄せます。
 */

/** いま本番として扱うかどうか */
export function isProductionEnv(env: NodeJS.ProcessEnv = process.env): boolean {
  const dbEnv = String(env.DATABASE_ENV ?? "")
    .trim()
    .toLowerCase();
  const vercel = String(env.VERCEL_ENV ?? "")
    .trim()
    .toLowerCase();
  return dbEnv === "production" || vercel === "production";
}
