/**
 * お手本の送り口（MockMailProvider）。
 *
 * ═══════════════════════════════════════════════════════
 * ★確認用では、本当に送らないこと
 * ═══════════════════════════════════════════════════════
 *
 *   確認用のデータには、架空のお名前が入っています。
 *   ですが、メールアドレスの打ち間違いは必ず起きます。
 *   1文字違いのアドレスが実在すれば、それは他人に届きます。
 *
 *   届いた人にとっては、身に覚えのない
 *   「パスワードの再設定」のメールです。
 *   こちらの確認作業のために、他人を不安にさせることになります。
 *
 *   ★だから、確認用では送りません。サーバーの記録に書くだけにします。
 *     記録は運営者だけが読めます。動きの確認はそれでできます。
 *
 * ═══════════════════════════════════════════════════════
 * ★本文を、そのまま画面へ返さないこと
 * ═══════════════════════════════════════════════════════
 *
 *   「確認用なので、再設定のリンクを画面に出せば早い」
 *   これをやると、メールアドレスを入れただけの人に
 *   リンクが渡ります。つまり、誰でも誰にでも成りすませます。
 *
 *   確認用であっても、そこは同じにしません。
 *   だから、この送り口も本文を戻り値に入れません。
 *   本文はサーバーの記録にだけ書きます。
 */

import type { Delivery, Mail, MailProvider, Preflight } from "./types";
import { MAIL_KIND_LABEL } from "./types";

export class MockMailProvider implements MailProvider {
  readonly name = "MOCK";
  readonly kind = "MOCK" as const;

  preflight(): Preflight {
    /* ★ここで ok:false を返さないこと。
         Mock は「設定漏れ」という状態を持ちません。
         本番で Mock を使わせない判断は、この中ではなく
         送り口を選ぶところ（index.ts）で1か所にまとめています。
         2か所で判断すると、片方だけ直したときにすり抜けます。 */
    return {
      ok: true,
      provider: this.name,
      note: "確認用の送り口です。外へは1通も出しません。サーバーの記録にだけ書きます。",
    };
  }

  async send(mail: Mail): Promise<Delivery> {
    /* ★宛先と件名だけでなく、本文も残すこと。
         リンクが正しく作れているかを、ここでしか確かめられません。
         この記録を読めるのは、サーバーの記録を見られる人だけです。 */
    console.info(
      [
        "──────── メール（確認用・実際には送っていません） ────────",
        `種類　： ${MAIL_KIND_LABEL[mail.kind] ?? mail.kind}`,
        `宛先　： ${mail.to}`,
        `件名　： ${mail.subject}`,
        "本文　：",
        mail.body,
        "────────────────────────────────────────────",
      ].join("\n"),
    );

    /* ★"SENT" を返さないこと。外へは出ていません。
         ここで嘘をつくと、あとから記録を読む人が
         「お客様には届いていたはずだ」と誤解します。 */
    return { via: "LOG", provider: this.name, ref: null };
  }
}
