/**
 * 景品の相場。
 *
 * ═══════════════════════════════════════════════════════
 * ★なぜ、画面の中から出してここに置いたのか
 * ═══════════════════════════════════════════════════════
 *
 *   相場の一覧は、もともと相場ウォッチの画面の中に書いてありました。
 *   そのぶん、ダッシュボードからは見えませんでした。
 *
 *   すると、こうなります。
 *
 *       相場ウォッチ  … 「2点、相場が取れていません」
 *       ダッシュボード … 何も出ない
 *
 *   朝いちばんにダッシュボードしか見ない人には、
 *   相場が止まっていることが一生伝わりません。
 *   伝わらないまま、古い値で計算された還元率を見て、
 *   「大丈夫そうだ」と判断します。
 *
 *   だから、置き場所を1つにします。
 *   ダッシュボードも相場ウォッチも、ここだけを見ます。
 *
 * ═══════════════════════════════════════════════════════
 * ★取れていない値を「変わっていない」と出さないこと
 * ═══════════════════════════════════════════════════════
 *
 *   相場の取得は、相手先の都合で止まります。
 *   止まっているのに前の値を出し続けると、
 *   「変わっていないから大丈夫」と読まれます。
 *   これがいちばん危険です。
 *
 *   取れていないものは at を null にします。
 *   null は「変わっていない」ではありません。「分からない」です。
 *
 * ★ここに出ている景品と価格は、すべて架空です。
 *   実在の商品の相場ではありません。
 */

/** 値上がりを「要対応」と見なす線（％） */
export const MARKET_SPIKE_PERCENT = 10;

export type MarketRow = {
  name: string;
  /** ガチャを作ったときの仕入れ値（円） */
  base: number;
  /** いま表示している値（円）。取れていないときは、前回取れた値 */
  now: number;
  /** 相場をいつ取れたか。取れていないなら null */
  at: string | null;
  /** この景品を使っているガチャ */
  usedIn: string;
};

/** ★すべて架空の景品です */
export const MARKET_ROWS: MarketRow[] = [
  { name: "デモ景品A（S賞相当）", base: 42_000, now: 58_000, at: "2026-08-22 11:30", usedIn: "腕時計 ハイエンド 3000" },
  { name: "デモ景品B（A賞相当）", base: 18_000, now: 21_400, at: "2026-08-22 11:30", usedIn: "腕時計 ハイエンド 3000" },
  { name: "デモ景品C（S賞相当）", base: 26_000, now: 27_100, at: "2026-08-22 11:30", usedIn: "プレミアムカード 500" },
  { name: "デモ景品D（A賞相当）", base: 9_800, now: 9_600, at: "2026-08-22 11:30", usedIn: "プレミアムカード 500" },
  { name: "デモ景品E（S賞相当）", base: 31_000, now: 31_000, at: null, usedIn: "スニーカー BOX 1000" },
  { name: "デモ景品F（B賞相当）", base: 4_200, now: 4_050, at: "2026-08-22 11:30", usedIn: "スニーカー BOX 1000" },
];

/** 作ったときからの変化（％） */
export function marketRate(r: MarketRow): number {
  return ((r.now - r.base) / r.base) * 100;
}

/**
 * 相場のまとめ。
 *
 * ★spiked に、相場が取れていないものを混ぜないこと。
 *   取れていない景品の「変化率」は、計算できるだけで意味がありません。
 *   意味のない数字を「値上がり」に混ぜると、
 *   本当に値上がりしたものが埋もれます。
 */
export function marketSummary(rows: MarketRow[] = MARKET_ROWS) {
  const spiked = rows.filter(
    (r) => r.at !== null && marketRate(r) >= MARKET_SPIKE_PERCENT,
  );
  const stale = rows.filter((r) => r.at === null);

  return {
    watched: rows.length,
    spiked,
    stale,
    /** 値上がりの影響を受けるガチャ */
    affected: new Set(spiked.map((r) => r.usedIn)),
  };
}
