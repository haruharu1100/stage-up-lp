/**
 * お客様の問い合わせに、AIが答えられるかどうかを決める。
 *
 * ═══════════════════════════════════════════════════════
 * ★このファイルでいちばん大事なこと
 * ═══════════════════════════════════════════════════════
 *
 *   「答えられないことを、答えられないと言えること」です。
 *
 *   AIの問い合わせ対応で本当に困るのは、答えられないことではありません。
 *   答えられないのに、それらしい文章を返してしまうことです。
 *
 *     ・返金しますと言ってしまった
 *     ・届いていない商品を「発送済みです」と答えてしまった
 *     ・規約に無い例外を約束してしまった
 *
 *   一度お客様に文字で伝えてしまうと、後から取り消せません。
 *   だからここでは、答えてよい範囲を先に決めて、
 *   そこから外れたものは全部、人に回します。
 *
 * ═══════════════════════════════════════════════════════
 * ★AIが自分で答えてよいのは、記録を読めば決まることだけ
 * ═══════════════════════════════════════════════════════
 *
 *   発送状況・追跡番号・残高・抽選の履歴。
 *   これらは、データを見れば答えが1つに決まります。
 *   人が答えても、AIが答えても、同じ文章になります。
 *
 *   逆に、次のようなものは必ず人に回します。
 *
 *     ・返金、キャンセル、解約
 *     ・商品の傷、破損、中身違い
 *     ・不正の疑い、アカウントの停止
 *     ・規約の例外をお願いされているもの
 *
 *   これらは「その場の判断」が要ります。
 *   判断とは、責任を取れる人が決めることです。AIは責任を取れません。
 *
 * ═══════════════════════════════════════════════════════
 * ★書いてはいけない言葉（景品表示法）
 * ═══════════════════════════════════════════════════════
 *
 *   「必ず当たります」「絶対に儲かります」のような断定は書きません。
 *   確率や期待値について、有利に見える言い方をしないこと。
 *   ここは営業の場所ではなく、事実をお伝えする場所です。
 */

import type { Order, Prize, PointEntry } from "./state";

/** AIが出した結論 */
export type AiAnswer =
  /** AIが自分で答えた */
  | { kind: "ANSWERED"; text: string }
  /**
   * AIは答えず、人に回した。
   *
   * draft は「人が手を入れて送るための下書き」です。
   * 下書きのまま自動で送ることはありません。
   */
  | { kind: "ESCALATE"; reason: string; draft: string };

/** AIが答えるために見る、そのお客様の状況 */
export type AskContext = {
  userName: string;
  balance: number;
  orders: Order[];
  prizes: Prize[];
  ledger: PointEntry[];
};

/** 発送の状態を、お客様に見せる日本語にする */
export const ORDER_STATUS_LABEL: Record<Order["status"], string> = {
  UNSHIPPED: "発送依頼済み",
  PREPARING: "商品手配中",
  SHIPPED: "発送済み",
  IN_TRANSIT: "配送中",
  DELIVERED: "配達完了",
};

/**
 * 人に回すべき言葉。
 *
 * ★ここは「疑わしいものは全部人へ」の側に倒すこと。
 *   AIが答えられる範囲を広げるほど、事故の種類が増えます。
 *   人の手間より、間違った回答を送ってしまう方がずっと高くつきます。
 */
const ESCALATE_RULES: { words: string[]; reason: string; draft: string }[] = [
  {
    words: ["傷", "きず", "破損", "壊れ", "こわれ", "汚れ", "違う商品", "中身が違", "不良"],
    reason: "商品の状態に関するお申し出です。現物を確認しないと判断できないため、AIは回答しません。",
    draft:
      "このたびはご不便をおかけし、申し訳ございません。商品の状態を確認したく存じます。" +
      "お手数ですが、該当箇所のお写真をお送りいただけますでしょうか。確認のうえ、対応をご案内いたします。",
  },
  {
    words: ["返金", "返品", "キャンセル", "取り消", "解約", "退会"],
    reason: "返金・解約の可否は規約とその場の判断が要るため、AIは回答しません。",
    draft:
      "お問い合わせありがとうございます。ご要望の内容について、担当者が確認のうえご連絡いたします。" +
      "差し支えなければ、詳しいご事情をお聞かせください。",
  },
  {
    words: ["凍結", "ログインできない", "停止", "不正", "乗っ取", "身に覚えのない"],
    reason: "アカウントの安全に関わる内容のため、AIは回答しません。運営者が確認します。",
    draft:
      "ご連絡ありがとうございます。お客様のアカウントについて確認しております。" +
      "安全のため、確認が取れるまでお時間をいただく場合がございます。",
  },
  {
    words: ["確率を教え", "当たりやすい", "設定を", "還元率", "operator", "仕込"],
    reason: "抽選の内部設定に関するご質問です。回答範囲を運営者が決める必要があるため、AIは回答しません。",
    draft:
      "お問い合わせありがとうございます。賞の内容と本数は商品ページに記載しております。" +
      "そのほかのご質問については、担当者よりご案内いたします。",
  },
];

/**
 * 問い合わせに、AIが答える。
 *
 * ★判断できないものを、無理に答えないこと。
 *   最後の default は「分からないので人へ回す」です。
 *   ここを「それらしい定型文を返す」に変えないこと。
 */
export function aiAnswer(question: string, ctx: AskContext): AiAnswer {
  const q = question.trim();
  if (!q) {
    return {
      kind: "ESCALATE",
      reason: "本文が空でした。",
      draft: "お問い合わせ内容を確認できませんでした。お手数ですが、もう一度お送りください。",
    };
  }

  /* ① まず、人に回すものを先に判定する。
     「発送された商品に傷があった」のように、
     答えられる言葉と答えられない言葉が両方入っている場合があります。
     その場合は、必ず人に回す側を優先します。 */
  for (const rule of ESCALATE_RULES) {
    if (rule.words.some((w) => q.includes(w))) {
      return { kind: "ESCALATE", reason: rule.reason, draft: rule.draft };
    }
  }

  /* ② 発送について。記録を読めば答えが決まる */
  if (/発送|届|配送|いつ|到着|追跡|伝票/.test(q)) {
    const live = ctx.orders.filter((o) => o.status !== "DELIVERED");
    if (ctx.orders.length === 0) {
      return {
        kind: "ANSWERED",
        text:
          "現在、発送のご依頼をお預かりしておりません。" +
          "獲得商品から「発送する」をお選びいただくと、発送の手配を開始いたします。",
      };
    }
    const lines = (live.length > 0 ? live : ctx.orders).map((o) => {
      const st = ORDER_STATUS_LABEL[o.status];
      const track =
        o.tracking && o.carrier
          ? `（${o.carrier}／お問い合わせ番号 ${o.tracking}）`
          : "（追跡番号は発送時にお知らせします）";
      return `・${o.prize}：${st}${track}`;
    });
    return {
      kind: "ANSWERED",
      text:
        `${ctx.userName}様のご依頼状況をお調べしました。\n` +
        lines.join("\n") +
        "\n\n最新の状況は、マイページの「発送手配中」からいつでもご確認いただけます。",
    };
  }

  /* ③ ポイントについて。台帳を読めば答えが決まる */
  if (/ポイント|pt|残高|履歴|減っ|増え/.test(q)) {
    const recent = ctx.ledger.slice(-3).reverse();
    const lines = recent.map(
      (e) =>
        `・${e.at}　${e.delta >= 0 ? "+" : ""}${e.delta.toLocaleString()}pt　${e.memo}`,
    );
    return {
      kind: "ANSWERED",
      text:
        `現在の残高は ${ctx.balance.toLocaleString()}pt です。\n` +
        (lines.length > 0 ? `直近の動きは次のとおりです。\n${lines.join("\n")}\n\n` : "") +
        "すべての内訳は、マイページの「ポイント履歴」からご確認いただけます。",
    };
  }

  /* ④ 獲得商品について */
  if (/獲得|当たった|景品|商品|交換/.test(q)) {
    const unchosen = ctx.prizes.filter((p) => p.status === "UNCHOSEN");
    return {
      kind: "ANSWERED",
      text:
        `${ctx.userName}様の獲得商品は ${ctx.prizes.length} 点です。` +
        (unchosen.length > 0
          ? `そのうち ${unchosen.length} 点が、お受け取り方法をお選びいただける状態です。` +
            "マイページの「獲得商品」から、現物のお届けかポイントへの交換をお選びください。"
          : "お受け取り方法の選択が済んでいない商品はございません。") +
        "\n\nなお、ポイントに交換した商品は、その後の発送はできません。",
    };
  }

  /* ⑤ ここまでで決まらなかったものは、全部人に回す。
     ★「よくあるご質問をご覧ください」で締めないこと。
       それは答えていないのに、答えた形になってしまいます */
  return {
    kind: "ESCALATE",
    reason: "お問い合わせ内容から、回答してよい範囲かどうかを判断できませんでした。",
    draft:
      "お問い合わせありがとうございます。いただいた内容について、担当者が確認のうえご連絡いたします。" +
      "お急ぎの場合は、その旨をお知らせください。",
  };
}
