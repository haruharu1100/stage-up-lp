/**
 * フッターに常設する6つのページの「名前」だけを置く場所。
 *
 * ═══════════════════════════════════════════════════════
 * ★なぜ、わざわざ別のファイルにしたのか
 * ═══════════════════════════════════════════════════════
 *
 *   この6つの名前は、もともと lib/console/shopInfo.ts の中にありました。
 *   ところが、そのファイルの先頭には 「ブラウザ側の道具です」という札（use client）が付いています。
 *   「ブラウザの中で動く道具です」という札です。
 *
 *   サーバー側で作る画面（app/store/[doc]/page.tsx）が、
 *   その札の付いたファイルから isShopDoc を借りると、
 *   借りたものが「本物の関数」ではなく「入れ物の影」になります。
 *   そのため、押した瞬間にこうなりました。
 *
 *       /store/company  → 500（画面が真っ白）
 *       /store/legal    → 500
 *       /store/terms    → 500
 *       /store/privacy  → 500
 *
 *   特定商取引法の表記・利用規約・プライバシーポリシーは、
 *   「買う前の人」が必ず読めなければならないページです。
 *   そこが全部落ちていました（2026-09-06、お店側の通し確認で発覚）。
 *
 *   ★この6つの名前を、"use client" の付いたファイルへ戻さないこと。
 *     戻した日から、同じように4ページが落ちます。
 *
 * ═══════════════════════════════════════════════════════
 * ★この6つを減らさないこと
 * ═══════════════════════════════════════════════════════
 *
 *   特定商取引法・利用規約・プライバシーポリシー・問い合わせ先は、
 *   「買う前の人」がいつでも読めるところに無ければなりません。
 *   奥まった場所に1つずつ置くのではなく、
 *   どの画面のいちばん下にも同じ並びで出します。
 */

export const SHOP_DOCS = [
  "company",
  "legal",
  "terms",
  "privacy",
  "faq",
  "contact",
] as const;

export type ShopDoc = (typeof SHOP_DOCS)[number];

export const SHOP_DOC_LABEL: Record<ShopDoc, string> = {
  company: "会社情報",
  legal: "特定商取引法に基づく表記",
  terms: "利用規約",
  privacy: "プライバシーポリシー",
  faq: "よくあるご質問",
  contact: "お問い合わせ",
};

export function isShopDoc(v: string): v is ShopDoc {
  return (SHOP_DOCS as readonly string[]).includes(v);
}
