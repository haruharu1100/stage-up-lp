/**
 * 「いまログインしている人」の形。
 *
 * ═══════════════════════════════════════════════════════
 * ★なぜ、型だけを別のファイルに置くのか
 * ═══════════════════════════════════════════════════════
 *
 *   この形は、サーバー側（lib/server/pageAuth.ts）が作り、
 *   ブラウザ側（components/console/ClientConsole.tsx）が受け取ります。
 *
 *   ブラウザ側のファイルから、サーバー側のファイルを
 *   直接 import すると、次のことが起こり得ます。
 *
 *       サーバー専用の部品（next/headers・DB接続）が、
 *       ブラウザ向けの荷物に混ざる
 *
 *   型だけを取り出すつもりでも、書き方を1つ間違えると混ざります。
 *   混ざったことに気づくのは、たいてい公開したあとです。
 *
 *   だから、両方から安全に読める場所に、形だけを置きます。
 *   ここには、動くもの（関数・DB・環境変数）を置かないこと。
 *
 * ═══════════════════════════════════════════════════════
 * ★内部のIDを、ここに入れないこと
 * ═══════════════════════════════════════════════════════
 *
 *   この形は、そのままブラウザへ渡ります。
 *   入れたものは、全部お客様に見えると思ってください。
 *   画面で使うのは、表示用の番号（displayId）だけで足ります。
 */

import type { Role } from "./permissions";

export type PageUser = {
  /** 画面に出してよい表示用の番号。★内部IDではありません */
  displayId: string;
  name: string;
  email: string;
  /** ★必ずサーバーがDBから読んだ値。画面側で作らないこと */
  role: Role;
  mfaEnabled: boolean;
  /** 追加の本人確認（2段階認証）を、このセッションで済ませたか */
  stepUpDone: boolean;
  tenantCode: string;
  tenantName: string;
};
