/**
 * 日本語を「変な場所で折り返さない」ようにするための道具。
 *
 * ═══════════════════════════════════════════════
 * ★以前のやり方と、なぜやめたか（重要・戻さないこと）
 * ═══════════════════════════════════════════════
 *
 *   以前は、文字と文字のあいだに「幅ゼロの見えない文字」（U+2060）を
 *   直接はさんでいました。見た目は変わらず、どのブラウザでも折り返しを
 *   止められるので、確かに効きます。
 *
 *   しかし、書き出されるHTMLの本文が
 *     「オンラインガチャ」の1文字ごとのあいだに U+2060 が挟まった状態
 *   になります。見た目は同じでも、次の実害があります。
 *   （ここに実物を貼ると grep で引っかかってしまうので、言葉で書いています）
 *
 *     1. 検索エンジンが読む本文が、普通の日本語ではなくなる
 *     2. 画面の文字をコピーして貼ると、見えないゴミが付いてくる
 *     3. ページ内検索（⌘F）で「オンラインガチャ」が見つからない
 *     4. 読み上げソフトが不自然に読む可能性がある
 *     5. 将来この文章を編集画面から直すとき、扱いづらい
 *
 *   そこで、文字そのものには一切手を加えない方式に変えました。
 *
 * ═══════════════════════════════════════════════
 * ★いまのやり方
 * ═══════════════════════════════════════════════
 *
 *   守りたい言葉だけを <span class="nb"> で包みます。
 *   nb は globals.css で white-space: nowrap を当てているだけです。
 *
 *     本文データ  … 「確認する」（ただの日本語。特殊文字ゼロ）
 *     画面に出る形 … <span class="nb">確認する</span>
 *
 *   これなら、
 *     ・検索エンジンが読む本文は普通の日本語のまま
 *     ・コピーしても余計な文字が付かない
 *     ・⌘F でちゃんと見つかる
 *     ・Safari でも Chrome でも同じように効く（nowrap は大昔からある指定）
 *
 *   auto-phrase のような新しいCSSには頼っていません。
 *   Safari が対応しておらず、iPhone でだけ「確／認する」と割れるためです。
 *
 * ═══════════════════════════════════════════════
 * ★使い方
 * ═══════════════════════════════════════════════
 *
 *   画面に出すとき   <p>{jp("公開後の実還元率を、管理画面で確認する。")}</p>
 *   属性に入れるとき  alt={plain("実還元率のグラフ")}   ← 包めないので素通し
 *
 *   ★jp() は「画面に出す部品」を返します。文字列ではありません。
 *     alt / aria-label / 3Dの文字 のような、タグを入れられない場所では
 *     使えません。そこは元の文字列をそのまま渡してください。
 *
 * ═══════════════════════════════════════════════
 * ★用語集に足すときの注意
 * ═══════════════════════════════════════════════
 *
 *   ・長い言葉から先に書くこと（「実還元率」を「還元率」より先に）
 *   ・8文字を超える言葉は入れないこと。
 *     折り返せる場所が無くなって、画面からはみ出します。
 */

import { Fragment, type ReactNode } from "react";

/**
 * 途中で割ってはいけない言葉。
 *
 * ここに無い言葉が割れていたら、まずここに足す。
 */
export const NO_BREAK_TERMS = [
  /* 製品名・固有名詞 */
  "AI GACHA OS",
  "AI OPERATOR",
  "CUSTOMER VIEW",
  "オンラインガチャ",
  "ラストワン賞",
  "バックテスト",
  /* 数字まわり（読み違えると事故になる言葉） */
  "設定還元率",
  "設定時還元率",
  "目標還元率",
  "実還元率",
  "還元率",
  "市場価格",
  "販売停止",
  "赤字確率",
  "在庫切れ",
  /* 画面・機能の名前 */
  "管理画面",
  "発送依頼",
  "発送管理",
  "価格監視",
  /*
    ★「監視」は2文字だけれど、必ず入れておくこと。
      「リアルタイム監視」のような言葉が狭い列に入ると、
      「リアルタイム監」／「視」と、熟語の途中で割れます。
      「監視」を守ると「リアルタイム」／「監視」で折れて、読めます。
  */
  "監視",
  "問い合わせ",
  "ガチャ設計",
  "無料デモ",
  "導入相談",
  "自動化",
  /* 動作（ボタンや説明文でよく割れる） */
  "確認する",
  "承認する",
  "相談する",
  "検討する",
  "体験する",
] as const;

/** 正規表現に使えない文字を無害にする */
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** 長い言葉から先に当てる（「実還元率」が「還元率」に食われないように） */
const RE = new RegExp(
  `(${[...NO_BREAK_TERMS]
    .sort((a, b) => b.length - a.length)
    .map(esc)
    .join("|")})`,
  "g",
);

/**
 * 文章を「守る言葉」と「それ以外」に切り分ける。
 * 文字は1文字も足さない・削らない（つなげ直すと必ず元に戻る）。
 */
export function splitJp(text: string): { t: string; nb: boolean }[] {
  const out: { t: string; nb: boolean }[] = [];
  let last = 0;
  RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = RE.exec(text)) !== null) {
    if (m.index > last) out.push({ t: text.slice(last, m.index), nb: false });
    out.push({ t: m[0], nb: true });
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push({ t: text.slice(last), nb: false });
  return out;
}

/**
 * 画面に出す日本語。守るべき言葉だけを、折り返さない形で包んで返す。
 *
 * ★文字そのものは変えません。包むだけです。
 */
export function jp(text: string): ReactNode {
  if (!text) return text;
  const parts = splitJp(text);
  if (parts.length === 1 && !parts[0].nb) return text;
  return (
    <>
      {parts.map((p, i) =>
        p.nb ? (
          <span key={i} className="nb">
            {p.t}
          </span>
        ) : (
          <Fragment key={i}>{p.t}</Fragment>
        ),
      )}
    </>
  );
}

/**
 * タグを入れられない場所（alt・aria-label・3Dの文字など）で使う。
 *
 * ★中身は「そのまま返すだけ」です。
 *   わざわざ関数にしてあるのは、「ここは守れていない」と
 *   コードを読んだ人に分かるようにするためです。
 *   ここで割れて困る言葉が出たら、文章のほうを短くして直します。
 */
export function plain(text: string): string {
  return text;
}
